const KEYS = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";

/** 64칸 색 배열 ("#rrggbb") */
export function faceDots(face: FaceData): string[] {
  return face.rows.flatMap((row) => [...row].map((k) => face.colors[KEYS.indexOf(k)]));
}
